import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.AERO_TEST_URL || 'http://127.0.0.1:4322';
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const errors = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', error => errors.push(error.message));
await mkdir('.qa/rev11', { recursive: true });
try {
  await page.goto(`${base}/software/aero/`);
  await page.locator('[data-nozzle-explorer]').scrollIntoViewIfNeeded();
  await page.locator('[data-nozzle-viewport] canvas').waitFor();
  assert.equal(await page.locator('h1').count(), 1);
  assert.equal(await page.locator('.aero-disclosure').getAttribute('open'), null);
  assert.equal(await page.locator('.technical-disclosure').getAttribute('open'), null);
  const order = await page.evaluate(() => document.querySelector('[data-pipeline-film]').compareDocumentPosition(document.querySelector('.aero-instance-tabs')));
  assert.ok(order & 4, 'Workspace choices must follow the video');
  await page.locator('#throat-radius').fill('10');
  await page.waitForFunction(() => document.querySelector('[data-area]').textContent === '314.2 mm²');
  assert.equal(await page.locator('[data-velocity]').textContent(), '27.05 m/s');
  assert.equal(await page.locator('[data-ratio]').textContent(), '5.76');
  assert.ok(await page.locator('[data-view="mesh"]').isDisabled());
  assert.ok(await page.locator('[data-view="result"]').isDisabled());
  assert.match(await page.locator('[data-preview-status]').textContent(), /do not apply/);
  await page.locator('[data-nozzle-explorer]').screenshot({ path: '.qa/rev11/changed-nozzle.png' });
  await page.locator('[data-reset]').click();
  assert.equal(await page.locator('#throat-radius').inputValue(), '8');
  await page.locator('[data-view="mesh"]').click();
  await page.waitForFunction(() => document.querySelector('[data-view-caption]').textContent.includes('12,600'));
  await page.locator('[data-nozzle-explorer]').screenshot({ path: '.qa/rev11/recorded-mesh.png' });
  await page.locator('[data-view="result"]').click();
  await page.waitForFunction(() => document.querySelector('[data-view-caption]').textContent.includes('101,798'));
  await page.locator('[data-nozzle-explorer]').screenshot({ path: '.qa/rev11/recorded-pressure.png' });
  await page.locator('.aero-disclosure > summary').click();
  const rows = await page.locator('.proof-results tbody tr').allTextContents();
  const result = JSON.parse(await readFile('public/demos/aero/wall-refinement-v6/engineering-result.json', 'utf8'));
  result.meshStudy.levels.forEach((level, index) => {
    assert.ok(rows[index].includes(level.cellCount.toLocaleString('en-US')));
    assert.ok(rows[index].includes(level.metricValue.toFixed(3)));
  });
  assert.equal(await page.locator('.proof-evidence a').getAttribute('href'), '/demos/aero/wall-refinement-v6/engineering-result.json');
  await page.goto(`${base}/software/aero/report/`);
  assert.match(await page.locator('.verdict').textContent(), /NOT ESTABLISHED/);
  assert.equal(await page.locator('tbody tr').count(), 3);
  await page.goto(`${base}/software/aero/demo/?example=cooling-channel`);
  assert.match(await page.locator('[data-guided-case-label]').textContent(), /Cooling/i);
  await page.goto(`${base}/software/aero/demo/?example=wall-refinement`);
  await page.locator('[data-guided-stage]').nth(3).locator('button').click();
  await page.waitForFunction(() => document.querySelector('[data-tour-model] .tour-field-label')?.textContent.includes('Recorded solver boundary'));
  await page.locator('[data-tour-model] canvas').waitFor();
  await page.goto(`${base}/software/aero/demo/?mode=current`);
  assert.match(await page.locator('.guided-response-disclosure').textContent(), /Live model chat is not connected/);
  await page.goto(`${base}/software/aero/`);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload();
  await page.locator('[data-nozzle-explorer]').scrollIntoViewIfNeeded();
  await page.locator('[data-nozzle-viewport] canvas').waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile horizontal overflow');
  assert.ok(await page.locator('video').evaluate(video => video.paused), 'Reduced-motion video must not autoplay');
  await page.screenshot({ path: '.qa/rev11/mobile.png', fullPage: true });
  const checksums = JSON.parse(await readFile('public/demos/aero/wall-refinement-v6/checksums.json', 'utf8'));
  for (const [file, expected] of Object.entries(checksums.files)) {
    const data = await readFile(`public/demos/aero/wall-refinement-v6/${file}`);
    assert.equal(createHash('sha256').update(data).digest('hex'), expected, `Checksum: ${file}`);
  }
  assert.deepEqual(errors, [], 'No browser JavaScript exceptions');
  console.log('PASS: ordering, collapsed details, slider math, stale-result lock, reset, recorded mesh/pressure, evidence alignment, report, example routing, chat disclosure, mobile, reduced motion, checksums, JavaScript errors.');
} finally { await browser.close(); }
